/**
 * Regenerates src/abi.ts from the Foundry build (`forge build` in contracts/arc). The generated
 * file is committed (like programs/escrow/idl) so the package works without Foundry installed.
 *   cd contracts/arc && forge build && cd - && pnpm --filter @hedged/arc abi:sync
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../../contracts/arc/out/", import.meta.url));
const read = (name: string) =>
  JSON.parse(readFileSync(`${root}${name}.sol/${name}.json`, "utf8")) as {
    abi: unknown[];
    bytecode: { object: string };
  };

const escrow = read("HedgedEscrow");
const mock = read("MockUSDC");
const out = `// GENERATED by scripts/abi-sync.ts from contracts/arc (forge build). Do not edit by hand.
export const HEDGED_ESCROW_ABI = ${JSON.stringify(escrow.abi, null, 2)} as const;

export const HEDGED_ESCROW_BYTECODE = "${escrow.bytecode.object}" as const;

/** TEST/LOCAL ONLY (anvil): 6-decimal stand-in for Arc's USDC ERC-20 interface. */
export const MOCK_USDC_ABI = ${JSON.stringify(mock.abi, null, 2)} as const;

export const MOCK_USDC_BYTECODE = "${mock.bytecode.object}" as const;
`;
writeFileSync(fileURLToPath(new URL("../src/abi.ts", import.meta.url)), out);
console.log("wrote src/abi.ts", {
  escrowAbiItems: escrow.abi.length,
  mockAbiItems: mock.abi.length,
});
